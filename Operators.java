public class Operators {
    public static void main(String[] args) {
        int x = 55;
        int y = 500;
        System.out.println(x + y); 
        System.out.println(x - y); 
        System.out.println(x * y); 
        System.out.println(x / y); 
        System.out.println(x % y); 
    }
    
}
