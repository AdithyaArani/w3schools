public class ifelse {
    public static void main(String[] args) {
        if (20 > 18) {
            System.out.println("20 is greater than 18");
            int x = 20;
            int y = 16;
            if (x > y) {
                System.out.println("x is greater than y");
            } else {
                System.out.println("x is not greater than y");
            }
        }
    }

}